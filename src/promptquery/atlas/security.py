"""Generate the SQL that confines the report bot to a safe, tenant-scoped slice of Atlas.

Three independent layers, so no single mistake in the LLM or the validator can leak data:

1. A dedicated login role (``atlas_bot``) that is read-only, time-limited and has SELECT only
   on an allowlist of tables (and only non-sensitive columns on PII tables).
2. Row-Level Security on every tenant table, keyed on the transaction-local setting
   ``app.tenant_id``. A missing setting raises an error (fail closed).
3. The application validator (``promptquery.safety``) - defence in depth, not the boundary.

RLS is ENABLEd but never FORCEd, so Atlas's own connection (the table owner) is unaffected.
"""

from __future__ import annotations

from collections.abc import Iterable

from ..schema import Schema

ROLE = "atlas_bot"
TENANT_SETTING = "app.tenant_id"

# No access at all: credentials, sessions, API keys, audit/idempotency/job internals, RBAC
# config, tenant settings, and payroll (salary data).
DENY_TABLES: frozenset[str] = frozenset({
    "alembic_version",
    "core_users",
    "core_refresh_sessions",
    "core_api_keys",
    "core_audit_log",
    "core_idempotency_keys",
    "core_jobs",
    "core_permissions",
    "core_roles",
    "core_role_permissions",
    "core_user_roles",
    "adm_tenant_settings",
    "hr_payroll_runs",
    "hr_payroll_run_lines",
})

# Table-level access, minus these columns (PII / compensation).
DENY_COLUMNS: dict[str, frozenset[str]] = {
    "hr_employees": frozenset({
        "base_salary", "national_id", "tax_id", "date_of_birth", "bank_account",
    }),
}

TENANT_COLUMN = "tenant_id"
# adm_tenants is the tenant registry: it has no tenant_id, its own id is the tenant.
TENANT_ROOT_TABLE = "adm_tenants"


def _q(ident: str) -> str:
    return '"' + ident.replace('"', '""') + '"'


def allowed_tables(schema: Schema, extra_deny: Iterable[str] = ()) -> list[str]:
    deny = DENY_TABLES | set(extra_deny)
    return sorted(
        t.name for t in schema.tables if t.schema == "public" and t.name not in deny
    )


def allowed_columns(schema: Schema, table: str) -> list[str]:
    t = next(t for t in schema.tables if t.schema == "public" and t.name == table)
    denied = DENY_COLUMNS.get(table, frozenset())
    return [c.name for c in t.columns if c.name not in denied]


def tenant_tables(schema: Schema, tables: Iterable[str]) -> list[str]:
    by_name = {t.name: t for t in schema.tables if t.schema == "public"}
    return [
        n for n in tables
        if n in by_name and any(c.name == TENANT_COLUMN for c in by_name[n].columns)
    ]


def generate_role_sql(schema: Schema, extra_deny: Iterable[str] = ()) -> str:
    tables = allowed_tables(schema, extra_deny)
    out: list[str] = []
    w = out.append

    w("-- Generated by `python -m promptquery.atlas.security`. Do not edit by hand.")
    w("-- Apply as the Atlas owner:  psql -v bot_password=... -f atlas_bot_role.sql")
    w("")
    w("DO $$ BEGIN")
    w(f"  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '{ROLE}') THEN")
    w(f"    CREATE ROLE {ROLE} LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION;")
    w("  END IF;")
    w("END $$;")
    w(f"ALTER ROLE {ROLE} PASSWORD :'bot_password';")
    w(f"ALTER ROLE {ROLE} SET default_transaction_read_only = on;")
    w(f"ALTER ROLE {ROLE} SET statement_timeout = '15s';")
    w(f"ALTER ROLE {ROLE} SET idle_in_transaction_session_timeout = '30s';")
    w(f"ALTER ROLE {ROLE} SET lock_timeout = '2s';")
    w(f"ALTER ROLE {ROLE} SET search_path = public;")
    w("")
    w("-- Start from nothing, then grant exactly the allowlist.")
    w(f"REVOKE ALL ON SCHEMA public FROM {ROLE};")
    w(f"REVOKE ALL ON ALL TABLES IN SCHEMA public FROM {ROLE};")
    w(f"REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM {ROLE};")
    w(f"REVOKE ALL ON ALL FUNCTIONS IN SCHEMA public FROM {ROLE};")
    w(f"GRANT USAGE ON SCHEMA public TO {ROLE};")
    w("")
    for name in tables:
        if name in DENY_COLUMNS:
            cols = ", ".join(_q(c) for c in allowed_columns(schema, name))
            w(f"GRANT SELECT ({cols}) ON {_q(name)} TO {ROLE};")
        else:
            w(f"GRANT SELECT ON {_q(name)} TO {ROLE};")
    w("")
    w("-- Row-Level Security: a missing app.tenant_id raises an error (fail closed).")
    for name in tenant_tables(schema, tables):
        w(f"ALTER TABLE {_q(name)} ENABLE ROW LEVEL SECURITY;")
        w(f"DROP POLICY IF EXISTS bot_tenant ON {_q(name)};")
        w(
            f"CREATE POLICY bot_tenant ON {_q(name)} FOR SELECT TO {ROLE} "
            f"USING ({TENANT_COLUMN} = current_setting('{TENANT_SETTING}')::uuid);"
        )
    if TENANT_ROOT_TABLE in tables:
        n = _q(TENANT_ROOT_TABLE)
        w(f"ALTER TABLE {n} ENABLE ROW LEVEL SECURITY;")
        w(f"DROP POLICY IF EXISTS bot_tenant ON {n};")
        w(
            f"CREATE POLICY bot_tenant ON {n} FOR SELECT TO {ROLE} "
            f"USING (id = current_setting('{TENANT_SETTING}')::uuid);"
        )
    w("")
    return "\n".join(out)


def main() -> None:  # pragma: no cover - thin CLI
    import argparse

    from ..db import Database
    from ..schema import introspect

    ap = argparse.ArgumentParser(description="Print atlas_bot role/RLS SQL for a live Atlas DB")
    ap.add_argument("dsn", help="owner DSN of the Atlas database")
    args = ap.parse_args()
    with Database(args.dsn) as db:
        print(generate_role_sql(introspect(db)))


if __name__ == "__main__":  # pragma: no cover
    main()
